import { PGlite } from "@electric-sql/pglite";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { diffSchema } from "../src/diff.js";
import { emptySchema } from "../src/types.js";
import { validateDiff } from "../src/validate.js";
import { schemaFromSql, applyDiffAndExtract } from "./helpers.js";
import { compareSchemas } from "../src/validate.js";

let db: PGlite;
beforeAll(async () => { db = new PGlite(); });
afterAll(async () => { await db.close(); });

async function expectValidDiff(fromSql: string, toSql: string) {
  const from = fromSql ? await schemaFromSql(db, fromSql) : emptySchema();
  const to = toSql ? await schemaFromSql(db, toSql) : emptySchema();
  const ddl = diffSchema(from, to);
  // Validate by applying from + diff and comparing to expected
  const applied = await applyDiffAndExtract(db, fromSql, ddl);
  const errors = compareSchemas(applied, to);
  if (errors.length > 0) {
    const msg = errors.map((e) => `  ${e.message}`).join("\n");
    throw new Error(`Validation errors:\n${msg}\n\nDDL was:\n${ddl}`);
  }
  return { from, to, ddl };
}

// ---------------------------------------------------------------------------
// Foreign key cycles
// ---------------------------------------------------------------------------

describe("FK cycles", () => {
  it("handles 2-table cycle (A↔B)", async () => {
    await expectValidDiff(
      "",
      `CREATE TABLE a (id integer PRIMARY KEY, b_id integer);
       CREATE TABLE b (id integer PRIMARY KEY, a_id integer);
       ALTER TABLE a ADD CONSTRAINT a_b FOREIGN KEY (b_id) REFERENCES b(id);
       ALTER TABLE b ADD CONSTRAINT b_a FOREIGN KEY (a_id) REFERENCES a(id)`,
    );
  });

  it("handles 3-table cycle (A→B→C→A)", async () => {
    await expectValidDiff(
      "",
      `CREATE TABLE a (id integer PRIMARY KEY, c_id integer);
       CREATE TABLE b (id integer PRIMARY KEY, a_id integer);
       CREATE TABLE c (id integer PRIMARY KEY, b_id integer);
       ALTER TABLE a ADD CONSTRAINT a_c FOREIGN KEY (c_id) REFERENCES c(id);
       ALTER TABLE b ADD CONSTRAINT b_a FOREIGN KEY (a_id) REFERENCES a(id);
       ALTER TABLE c ADD CONSTRAINT c_b FOREIGN KEY (b_id) REFERENCES b(id)`,
    );
  });

  it("handles self-referencing FK", async () => {
    await expectValidDiff(
      "",
      `CREATE TABLE employees (
         id integer PRIMARY KEY,
         manager_id integer REFERENCES employees(id),
         name text NOT NULL
       )`,
    );
  });

  it("handles adding FK to existing tables in a cycle", async () => {
    await expectValidDiff(
      `CREATE TABLE a (id integer PRIMARY KEY, b_id integer);
       CREATE TABLE b (id integer PRIMARY KEY, a_id integer)`,
      `CREATE TABLE a (id integer PRIMARY KEY, b_id integer);
       CREATE TABLE b (id integer PRIMARY KEY, a_id integer);
       ALTER TABLE a ADD CONSTRAINT a_b FOREIGN KEY (b_id) REFERENCES b(id);
       ALTER TABLE b ADD CONSTRAINT b_a FOREIGN KEY (a_id) REFERENCES a(id)`,
    );
  });
});

