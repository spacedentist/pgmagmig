describe("functions and triggers", () => {
  it("creates function and trigger from empty", async () => {
    await expectValidDiff(
      "",
      `CREATE TABLE t (id integer, updated_at timestamptz);
       CREATE FUNCTION set_updated() RETURNS trigger AS $$
         BEGIN NEW.updated_at = now(); RETURN NEW; END;
       $$ LANGUAGE plpgsql;
       CREATE TRIGGER trg_updated BEFORE UPDATE ON t
         FOR EACH ROW EXECUTE FUNCTION set_updated()`,
    );
  });

  it("changes a trigger's function body", async () => {
    await expectValidDiff(
      `CREATE TABLE t (id integer);
       CREATE FUNCTION trg_fn() RETURNS trigger AS $$
         BEGIN RETURN NEW; END;
       $$ LANGUAGE plpgsql;
       CREATE TRIGGER trg BEFORE INSERT ON t
         FOR EACH ROW EXECUTE FUNCTION trg_fn()`,
      `CREATE TABLE t (id integer);
       CREATE FUNCTION trg_fn() RETURNS trigger AS $$
         BEGIN RAISE NOTICE 'inserted'; RETURN NEW; END;
       $$ LANGUAGE plpgsql;
       CREATE TRIGGER trg BEFORE INSERT ON t
         FOR EACH ROW EXECUTE FUNCTION trg_fn()`,
    );
  });

  it("drops a trigger", async () => {
    await expectValidDiff(
      `CREATE TABLE t (id integer);
       CREATE FUNCTION trg_fn() RETURNS trigger AS $$
         BEGIN RETURN NEW; END;
       $$ LANGUAGE plpgsql;
       CREATE TRIGGER trg BEFORE INSERT ON t
         FOR EACH ROW EXECUTE FUNCTION trg_fn()`,
      `CREATE TABLE t (id integer);
       CREATE FUNCTION trg_fn() RETURNS trigger AS $$
         BEGIN RETURN NEW; END;
       $$ LANGUAGE plpgsql`,
    );
  });

  it("adds a table using an existing function as default", async () => {
    await expectValidDiff(
      `CREATE SEQUENCE code_seq;
       CREATE FUNCTION next_code() RETURNS text AS $$
         BEGIN RETURN 'CODE-' || nextval('code_seq'); END;
       $$ LANGUAGE plpgsql`,
      `CREATE SEQUENCE code_seq;
       CREATE FUNCTION next_code() RETURNS text AS $$
         BEGIN RETURN 'CODE-' || nextval('code_seq'); END;
       $$ LANGUAGE plpgsql;
       CREATE TABLE items (id integer, code text DEFAULT next_code())`,
    );
  });
});

