// Multiple simultaneous changes
// ---------------------------------------------------------------------------

describe("multiple simultaneous changes", () => {
  it("handles add + drop + alter columns on same table", async () => {
    await expectValidDiff(
      `CREATE TABLE t (
         id integer PRIMARY KEY,
         old_col text,
         name text,
         count integer
       )`,
      `CREATE TABLE t (
         id integer PRIMARY KEY,
         name text NOT NULL,
         count bigint,
         new_col boolean DEFAULT false
       )`,
    );
  });

  it("handles changes across many tables at once", async () => {
    await expectValidDiff(
      `CREATE TABLE a (id integer PRIMARY KEY, x integer);
       CREATE TABLE b (id integer PRIMARY KEY, a_id integer REFERENCES a(id));
       CREATE TABLE c (id integer PRIMARY KEY)`,
      `CREATE TABLE a (id integer PRIMARY KEY, x bigint, y text);
       CREATE TABLE b (id integer PRIMARY KEY, a_id integer REFERENCES a(id), label text);
       CREATE TABLE d (id integer PRIMARY KEY, b_id integer REFERENCES b(id))`,
    );
  });

  it("handles full schema evolution (multi-step)", async () => {
    // Step 1: initial schema
    const v1 = `
      CREATE TABLE users (id SERIAL PRIMARY KEY, email text NOT NULL UNIQUE);
    `;
    // Step 2: add orders, modify users
    const v2 = `
      CREATE TABLE users (id SERIAL PRIMARY KEY, email text NOT NULL UNIQUE, name text);
      CREATE TABLE orders (id SERIAL PRIMARY KEY, user_id integer REFERENCES users(id));
      CREATE INDEX idx_orders_user ON orders (user_id);
    `;
    // Step 3: add products, modify orders
    const v3 = `
      CREATE TABLE users (id SERIAL PRIMARY KEY, email text NOT NULL UNIQUE, name text);
      CREATE TABLE products (id SERIAL PRIMARY KEY, name text NOT NULL, price numeric(10,2));
      CREATE TABLE orders (
        id SERIAL PRIMARY KEY,
        user_id integer REFERENCES users(id),
        product_id integer REFERENCES products(id),
        quantity integer NOT NULL DEFAULT 1
      );
      CREATE INDEX idx_orders_user ON orders (user_id);
      CREATE INDEX idx_orders_product ON orders (product_id);
    `;

    await expectValidDiff("", v1);
    await expectValidDiff(v1, v2);
    await expectValidDiff(v2, v3);
    await expectValidDiff(v1, v3); // skip v2
  });
});

